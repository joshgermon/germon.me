/**
 * Bakes "is this point over the United States?" as a 0.2° grid (≈20 km cells) over three boxes
 * (lower 48, Alaska, Hawaii), from Natural Earth 1:50m via world-atlas. The bake and the live
 * route both use it (domain/us-area.ts), so their counts agree.
 *
 *   pnpm tsx scripts/experiments/ground-stop/us-raster.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join } from 'node:path';

import { geoContains } from 'd3-geo';
import { feature } from 'topojson-client';
import type { Topology } from 'topojson-specification';

import { US_BOXES, US_CELL } from '../../../src/experiments/ground-stop/domain/us-area';

const require = createRequire(import.meta.url);
// SAFETY: world-atlas ships TopoJSON topologies; the shape is fixed by the package.
const countries = JSON.parse(
  readFileSync(require.resolve('world-atlas/countries-50m.json'), 'utf8'),
) as Topology;
const object = countries.objects['countries'];
if (object?.type !== 'GeometryCollection') throw new Error('world-atlas: no countries');
const us = feature(countries, object).features.find((f) => String(f.id) === '840');
if (!us) throw new Error('world-atlas: no United States');

const chunks: string[] = [];
let inside = 0;
for (const box of US_BOXES) {
  const rows = Math.round((box.north - box.south) / US_CELL);
  const cols = Math.round((box.east - box.west) / US_CELL);
  const bits = new Uint8Array(Math.ceil((rows * cols) / 8));
  for (let r = 0; r < rows; r++)
    for (let c = 0; c < cols; c++) {
      const lat = box.south + (r + 0.5) * US_CELL;
      const lon = box.west + (c + 0.5) * US_CELL;
      if (geoContains(us, [lon, lat])) {
        const i = r * cols + c;
        bits[i >> 3] = (bits[i >> 3] ?? 0) | (1 << (i & 7));
        inside++;
      }
    }
  chunks.push(Buffer.from(bits).toString('base64'));
}
writeFileSync(
  join(
    import.meta.dirname,
    '..',
    '..',
    '..',
    'src',
    'experiments',
    'ground-stop',
    'data',
    'us-raster.ts',
  ),
  `/** Generated by scripts/experiments/ground-stop/us-raster.ts. Do not edit. ${inside} cells inside. */\n\n/** One base64 bitset per box in domain/us-area.ts#US_BOXES, rows south to north. */\nexport const US_RASTER: readonly string[] = ${JSON.stringify(chunks, null, 2)};\n`,
);
console.warn(`us-raster: ${inside} cells`);
