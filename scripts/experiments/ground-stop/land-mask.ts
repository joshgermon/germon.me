/**
 * Bakes the globe's dot matrix: which points of a Fibonacci lattice fall on land, and which of
 * those are in the United States, as two base64 bitsets in src/data/land-mask.ts.
 *
 * Run `pnpm land` after changing the lattice size. Uses Natural Earth 1:50m (world-atlas,
 * public domain) and d3-geo's spherical point-in-polygon test, so nothing ships at runtime but
 * the bits.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join } from 'node:path';

import { geoContains } from 'd3-geo';
import type { GeoPermissibleObjects } from 'd3-geo';
import { feature } from 'topojson-client';
import type { Topology } from 'topojson-specification';

import { latticePoint, toLatLon } from '../../../src/experiments/ground-stop/domain/sphere.ts';

const N = 140_000;
const US_ID = '840';

const require = createRequire(import.meta.url);
const load = (file: string): Topology =>
  // SAFETY: world-atlas ships TopoJSON topologies; the shape is fixed by the package.
  JSON.parse(readFileSync(require.resolve(`world-atlas/${file}`), 'utf8')) as Topology;

const countries = load('countries-50m.json');
const landTopo = load('land-50m.json');
const landObject = landTopo.objects['land'];
const countryObject = countries.objects['countries'];
if (!landObject || !countryObject) throw new Error('world-atlas: missing objects');

if (countryObject.type !== 'GeometryCollection')
  throw new Error('world-atlas: countries is not a collection');
const land: GeoPermissibleObjects = feature(landTopo, landObject);
const us = feature(countries, countryObject).features.find((f) => String(f.id) === US_ID);
if (!us) throw new Error('world-atlas: United States not found');

const landBits = new Uint8Array(Math.ceil(N / 8));
const usBits = new Uint8Array(Math.ceil(N / 8));
let landCount = 0;
let usCount = 0;
for (let i = 0; i < N; i++) {
  const { lat, lon } = toLatLon(latticePoint(i, N));
  const point: [number, number] = [lon, lat];
  if (geoContains(land, point)) {
    landBits[i >> 3] = (landBits[i >> 3] ?? 0) | (1 << (i & 7));
    landCount++;
    if (geoContains(us, point)) {
      usBits[i >> 3] = (usBits[i >> 3] ?? 0) | (1 << (i & 7));
      usCount++;
    }
  }
}

const b64 = (bits: Uint8Array): string => Buffer.from(bits).toString('base64');
const out = `/**
 * Generated by scripts/land-mask.ts (\`pnpm land\`) from Natural Earth 1:50m. Do not edit.
 *
 * Bit i of each set is point i of a ${N.toLocaleString('en-US')}-point Fibonacci lattice
 * (domain/sphere.ts#latticePoint): ${landCount.toLocaleString('en-US')} land points, ${usCount.toLocaleString('en-US')} of them in the US.
 */

/** Points in the lattice. */
export const LATTICE_SIZE = ${N};

/** Land points, as a base64 little-endian bitset. */
export const LAND_BITS = '${b64(landBits)}';

/** United States points (a subset of land), as a base64 little-endian bitset. */
export const US_BITS = '${b64(usBits)}';
`;
writeFileSync(join(import.meta.dirname, '..', 'src', 'data', 'land-mask.ts'), out);
console.warn(`land-mask: ${landCount} land, ${usCount} US of ${N}`);
